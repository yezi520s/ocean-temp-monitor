def set_run_font(run, cn_font="宋体", en_font="Times New Roman", size=12, bold=False):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = en_font
    run._element.rPr.rFonts.set(qn("w:eastAsia"), cn_font)


def add_para(doc, text="", size=12, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
             first_indent=True, space_before=0, space_after=0, line=1.5,
             cn_font="宋体", en_font="Times New Roman", color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = line
    if first_indent:
        pf.first_line_indent = Pt(size * 2)
    run = p.add_run(text)
    set_run_font(run, cn_font, en_font, size, bold)
    if color:
        run.font.color.rgb = color
    return p


